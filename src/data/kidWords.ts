function uniqueCorpus(words: readonly string[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const raw of words) {
    const word = normalizeHebrew(raw)
    if (word.length < MIN_WORD_LENGTH || seen.has(word)) continue
    seen.add(word)
    out.push(word)
  }
  return out
}

export const KID_WORDS: readonly string[] = uniqueCorpus(RAW_KID_WORDS)
